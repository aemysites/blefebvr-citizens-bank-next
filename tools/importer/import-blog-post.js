/* global WebImporter */
/* eslint-disable no-console, class-methods-use-this */

/**
 * Import script for blog-post template
 *
 * Template: blog-post
 * Description: Blog post pages from ketointhecity.com with recipe content
 * Content Type: Default content only (no blocks)
 * Main Selector: article.BlogItem
 *
 * This script:
 * 1. Applies ketointhecity-cleanup transformer (beforeTransform hook)
 * 2. Extracts content from article.BlogItem container
 * 3. Applies WebImporter built-in rules (metadata, images, cleanup)
 * 4. Generates sanitized document paths
 */

// TRANSFORMER IMPORTS
import ketointhecityCleanup from './transformers/ketointhecity-cleanup.js';

// TRANSFORMER REGISTRY
const transformers = [
  ketointhecityCleanup,
];

// PAGE TEMPLATE CONFIGURATION - Embedded from page-templates.json
const PAGE_TEMPLATE = {
  name: 'blog-post',
  description: 'Blog post pages from ketointhecity.com with recipe content',
  urlPatterns: [
    '/blog/keto-recipe-*',
    '/blog/*'
  ],
  exampleUrls: [
    'https://ketointhecity.com/blog/keto-recipe-peanut-butter-cup-chia-pudding'
  ],
  sections: [
    {
      name: 'main-content',
      description: 'Main blog post article content - title, intro, image, recipe',
      selector: 'article.BlogItem',
      contentType: 'default',
      blocks: []
    }
  ],
  exclude: [
    {
      selector: '.Header',
      reason: 'Site header - handled by EDS header block'
    },
    {
      selector: '.Blog-meta.BlogItem-meta',
      reason: 'Blog metadata (categories, author, date, tags) - auto-generated by EDS blog'
    },
    {
      selector: '.BlogItem-share',
      reason: 'Social sharing buttons - EDS blog infrastructure'
    },
    {
      selector: '.BlogItem-pagination',
      reason: 'Previous/Next navigation - EDS blog navigation'
    },
    {
      selector: '.Footer',
      reason: 'Site footer - handled by EDS footer block'
    }
  ],
  metadata: {
    sourceType: 'squarespace-blog',
    contentFormat: 'default-content',
    hasBlocks: false,
    migrationNotes: 'Simple blog post with default content only - no blocks needed. All content extracted from article.BlogItem container.'
  }
};

/**
 * Execute all page transformers for a specific hook
 * @param {string} hookName - The hook name ('beforeTransform' or 'afterTransform')
 * @param {Element} element - The DOM element to transform (typically document.body or main)
 * @param {Object} payload - The payload containing { document, url, html, params }
 */
function executeTransformers(hookName, element, payload) {
  transformers.forEach((transformerFn) => {
    try {
      transformerFn.call(null, hookName, element, payload);
    } catch (e) {
      console.error(`Transformer failed at ${hookName}:`, e);
    }
  });
}

/**
 * Extract main content from the page
 * @param {Document} document - The DOM document
 * @param {Object} template - The embedded PAGE_TEMPLATE object
 * @returns {Element|null} The main content element or null if not found
 */
function extractMainContent(document, template) {
  const mainSection = template.sections.find(s => s.name === 'main-content');
  if (!mainSection) {
    console.warn('No main-content section defined in template');
    return null;
  }

  const mainContent = document.querySelector(mainSection.selector);
  if (!mainContent) {
    console.warn(`Main content not found with selector: ${mainSection.selector}`);
    return null;
  }

  console.log(`Extracted main content from: ${mainSection.selector}`);
  return mainContent;
}

// EXPORT DEFAULT CONFIGURATION
export default {
  /**
   * Main transformation function
   * Follows Helix Importer transform pattern
   *
   * @param {Object} payload - The transformation payload
   * @param {Document} payload.document - The DOM document
   * @param {string} payload.url - The document URL
   * @param {string} payload.html - The raw HTML string
   * @param {Object} payload.params - Additional parameters including originalURL
   * @returns {Array} Array of transformed elements with paths
   */
  transform: ({ document, url, html, params }) => {
    console.log(`Transforming blog post: ${params.originalURL}`);

    // 1. Execute beforeTransform transformers (initial cleanup)
    // The ketointhecity-cleanup transformer will remove:
    // - Squarespace announcement bars
    // - Mobile navigation overlays
    // - Site loaders and parallax effects
    // - Header, Footer (handled by EDS blocks)
    // - Blog metadata, sharing, pagination (auto-generated in EDS)
    executeTransformers('beforeTransform', document.body, { document, url, html, params });

    // 2. Extract main content from article.BlogItem
    const main = extractMainContent(document, PAGE_TEMPLATE);
    if (!main) {
      console.error('Failed to extract main content - returning empty result');
      return [];
    }

    // 3. Apply WebImporter built-in rules for default content
    // These rules handle:
    // - Metadata extraction (title, description, author, publication date)
    // - Background image conversion to <img> tags
    // - Image URL adjustment (relative to absolute)
    // - Link cleanup and URL normalization
    WebImporter.rules.createMetadata(main, document);
    WebImporter.rules.transformBackgroundImages(main, document);
    WebImporter.rules.adjustImageUrls(main, url, params.originalURL);

    // 4. Execute afterTransform transformers (final cleanup)
    executeTransformers('afterTransform', main, { document, url, html, params });

    // 5. Generate sanitized path (full localized path without extension)
    // Example: /blog/keto-recipe-peanut-butter-cup-chia-pudding
    const urlPath = new URL(params.originalURL).pathname;
    const path = WebImporter.FileUtils.sanitizePath(
      urlPath.replace(/\/$/, '').replace(/\.html$/, '')
    );

    console.log(`Generated path: ${path}`);

    // 6. Return transformed element with metadata
    return [{
      element: main,
      path,
      report: {
        template: PAGE_TEMPLATE.name,
        contentType: 'default',
        hasBlocks: false,
        url: params.originalURL,
        sections: [{
          name: 'main-content',
          selector: PAGE_TEMPLATE.sections[0].selector,
          contentType: 'default'
        }]
      }
    }];
  }
};
